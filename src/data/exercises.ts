const byId = new Map(exercises.map((exercise) => [exercise.id, exercise]));
const byCode = new Map(exercises.map((exercise) => [exercise.code, exercise]));

export function exerciseById(id: string): Exercise | undefined {
  return byId.get(id);
}

export function exerciseByCode(code: string): Exercise | undefined {
  return byCode.get(code);
}

export function mustExercise(id: string): Exercise {
  const exercise = byId.get(id);
  if (!exercise) throw new Error(`Ukjent øvelse ${id}`);
  return exercise;
}
