import type { Pt, Stick, StickPose, StickProp } from "../types";

export const STICK_KEYS = [
  "head",
  "shoulder",
  "hip",
  "knee",
  "ankle",
  "knee2",
  "ankle2",
  "elbow",
  "wrist",
  "elbow2",
  "wrist2",
  "toe",
  "toe2",
] as const;

export function nudge(stick: Stick, dx: number, dy: number): Stick {
  const next = {} as Stick;
  for (const key of STICK_KEYS) next[key] = [stick[key][0] + dx, stick[key][1] + dy];
  return next;
}

export function mixStick(a: Stick, b: Stick, t: number): Stick {
  const next = {} as Stick;
  for (const key of STICK_KEYS) {
    next[key] = [a[key][0] + (b[key][0] - a[key][0]) * t, a[key][1] + (b[key][1] - a[key][1]) * t];
  }
  return next;
}

function clamp(n: number, min: number, max: number): number {
  return Math.max(min, Math.min(max, n));
}

function toePoint(knee: Pt, ankle: Pt): Pt {
  if (ankle[1] >= 198) return [clamp(ankle[0] + 22, 8, 192), 214];
  const dx = ankle[0] - knee[0];
  const dy = ankle[1] - knee[1];
  const len = Math.hypot(dx, dy) || 1;
  return [clamp(ankle[0] + (dx / len) * 18, 6, 194), clamp(ankle[1] + (dy / len) * 18, 8, 214)];
}

function sk(
  head: Pt,
  shoulder: Pt,
  hip: Pt,
  knee: Pt,
  ankle: Pt,
  knee2: Pt,
  ankle2: Pt,
  elbow: Pt,
  wrist: Pt,
  elbow2: Pt,
  wrist2: Pt,
  toe?: Pt,
  toe2?: Pt,
): Stick {
  return {
    head, shoulder, hip, knee, ankle, knee2, ankle2, elbow, wrist, elbow2, wrist2,
    toe: toe ?? toePoint(knee, ankle),
    toe2: toe2 ?? toePoint(knee2, ankle2),
  };
}

function two(a: Stick, b: Stick, face: StickPose["face"] = "side", prop?: StickProp): StickPose {
  return prop ? { a, b, face, prop } : { a, b, face };
}

function breathe(a: Stick, face: StickPose["face"] = "side"): StickPose {
  return { a, b: nudge(a, 1, -2), face };
}

