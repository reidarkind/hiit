const byId = new Map(builtinSessions.map((session) => [session.id, session]));

export function builtinById(id: string): Session | undefined {
  return byId.get(id);
}

export function allSessions(state: AppState): Session[] {
  return [...builtinSessions, ...state.customSessions, ...state.receivedSessions];
}

export function findSession(state: AppState, id: string): Session | undefined {
  return builtinById(id) ?? state.customSessions.find((item) => item.id === id) ?? state.receivedSessions.find((item) => item.id === id);
}
