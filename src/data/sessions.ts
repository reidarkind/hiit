import type { AppState, Block, Session } from "../types";

function b(exerciseId: string, workSeconds: number, restSeconds: number, rounds?: number): Block {
  return rounds ? { exerciseId, workSeconds, restSeconds, rounds } : { exerciseId, workSeconds, restSeconds };
}

function s(id: string, name: string, summary: string, about: string, blocks: Block[]): Session {
  return { id, name, summary, about, blocks, builtin: true };
}

